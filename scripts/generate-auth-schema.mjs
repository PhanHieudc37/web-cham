import { readFileSync, writeFileSync, existsSync, unlinkSync } from "node:fs";
import { spawnSync } from "node:child_process";

const temporaryConfig = ".auth-generation.ts";
const target = "src/server/db/schema/auth.ts";
if (existsSync(temporaryConfig)) throw new Error("Temporary auth config already exists");

try {
  const config = readFileSync("src/server/auth/schema-config.ts", "utf8");
  // The CLI explicitly rejects server-only, even under the react-server condition.
  writeFileSync(temporaryConfig, config.replace('import "server-only";', ""));
  const args = ["--yes", "auth@1.7.14", "generate", "--config", temporaryConfig, "--adapter", "drizzle", "--dialect", "postgresql", "--output", target, "--yes"];
  const result = process.platform === "win32"
    ? spawnSync("cmd.exe", ["/d", "/s", "/c", `npx ${args.join(" ")}`], { stdio: "inherit" })
    : spawnSync("npx", args, { stdio: "inherit" });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error("Better Auth schema generation failed");

  const snakeCase = (name) => name.replace(/[A-Z]/g, (character) => `_${character.toLowerCase()}`);
  const generated = readFileSync(target, "utf8")
    .replace(/(text|boolean|timestamp)\("([A-Za-z_]+)"\)/g, (_, type, name) =>
      `${type}("${snakeCase(name)}"${type === "timestamp" ? ", { withTimezone: true }" : ""})`)
    .replace(/export const \w+ = pgTable\([\s\S]*?\n(?:\}\);|\);)/g, (table) => table.replace(/\);$/, ").enableRLS();"));
  writeFileSync(target, `import "server-only";\n\n// Generated by Better Auth 1.7.14; normalized by scripts/generate-auth-schema.mjs.\n${generated}`);
} finally {
  if (existsSync(temporaryConfig)) unlinkSync(temporaryConfig);
}
